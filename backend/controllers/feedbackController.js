const getFeedbackSlaHours = () => {
  const slaHours = Number(process.env.FEEDBACK_SLA_HOURS || 72);
  if (!Number.isFinite(slaHours) || slaHours <= 0 || slaHours > 720) {
    throw new Error('FEEDBACK_SLA_HOURS must be greater than 0 and no more than 720.');
  }
  return slaHours;
};

const getResponseDueAt = () => new Date(Date.now() + getFeedbackSlaHours() * 60 * 60 * 1000);

const addResponseDeadline = (record) => {
  const feedback = typeof record.toObject === 'function' ? record.toObject() : record;
  if (feedback.responseDueAt || !feedback.createdAt) return feedback;

  return {
    ...feedback,
    responseDueAt: new Date(
      new Date(feedback.createdAt).getTime() + getFeedbackSlaHours() * 60 * 60 * 1000
    )
  };
};

exports.submitFeedback = async (req, res) => {
  const errors = validationResult(req);
  if (!errors.isEmpty()) {
    return res.status(400).json({ message: errors.array()[0].msg, errors: errors.array() });
  }

  const { title, category, description, anonymous, priority, department, questionAnswers } = req.body;

  try {
    // Analyze sentiment
    const analysis = await analyzeSentiment(description);
    const aiSummaryResult = await summarizeQuestionnaire({
      category,
      title,
      description,
      priority,
      department,
      answers: questionAnswers
    });
    
    const feedback = new Feedback({
      title,
      category: category || analysis.suggestedCategory || aiSummaryResult.aiSummaryCategory || "General",
      description,
      anonymous: anonymous || false,
      priority: priority || "Medium",
      department,
      sentiment: analysis.sentiment,
      aiSuggestedCategory: analysis.suggestedCategory,
      aiSummary: aiSummaryResult.aiSummary,
      aiSummaryCategory: aiSummaryResult.aiSummaryCategory,
      aiSummaryTags: aiSummaryResult.aiSummaryTags,
      questionAnswers,
      questionCount: Object.keys(questionAnswers || {}).length,
      mood: aiSummaryResult.mood,
      moodScore: aiSummaryResult.moodScore,
      responseDueAt: getResponseDueAt(),
      submittedBy: req.user.id
    });

    await feedback.save();

    const scenarioResult = await categorizeMessage({
      message: `${title}\n${description}`,
      sourceType: 'feedback',
      sourceId: feedback._id
    });

    if (scenarioResult.safety) {
      feedback.priority = 'Urgent';
      await feedback.save();
    }

    try {
      const aiReply = await generateAIReply(feedback, scenarioResult.scenario);
      const reply = new Reply({
        feedbackId: feedback._id,
        generatedByAI: true,
        autoGenerated: true,
        aiDraft: aiReply,
        finalReply: aiReply,
        approvedByAdmin: true,
        sentToEmployee: true,
        createdBy: req.user.id
      });
      await reply.save();
      await Feedback.findByIdAndUpdate(feedback._id, { status: 'AI Auto Responded' });
    } catch (autoReplyError) {
      console.error('AI Auto-Response Error:', autoReplyError);
    }

    const io = req.app.get('io');
    if (io) {
      emitFeedbackEvent(io, 'feedback:created', feedback);
      if (scenarioResult.unmatched) {
        io.to('admins').emit('scenario:unmatched', { unmatchedId: scenarioResult.unmatched._id });
      }
    }

    res.status(201).json(feedback);
  } catch (err) {
    console.error(err);
    res.status(500).json({ message: "Server error" });
  }
};

